/** [tile] with a white logo, or a near-black one where the tile is too light for white. */
private fun onTile(tile: Long): LogoColors {
    val color = Color(tile)
    return LogoColors(color, if (color.luminance() > 0.5f) Color(0xFF1C1C1E) else Color.White)
}

